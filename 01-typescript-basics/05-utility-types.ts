// Q1: What is Partial<T>? When would you use it in a backend?
// A:  Partial<T> makes all properties of T optional. Use it for HTTP PATCH 
//     endpoints where the client may send only the fields they want to update.
//     Example: type UpdateUserDto = Partial<User>;
//
// Q2: What is the difference between Pick and Omit?
// A:  Pick<T, K> creates a type with ONLY the specified keys from T.
//     Omit<T, K> creates a type with ALL keys EXCEPT the specified ones.
//     Use Pick when you need a small subset; use Omit when you need most fields.
//
// Q3: How would you strip a password field before sending a user to the client?
// A:  Use Omit<User, "password"> for the type, and destructuring at runtime:
//     const { password, ...safeUser } = dbUser; return safeUser;
//     This is a real production pattern used in every backend.
//
// Q4: What is Record<K, V>? Give a real-world example.
// A:  Record creates an object type with keys of type K and values of type V.
//     Example: Record<string, number> is equivalent to { [key: string]: number }.
//     Real use: Record<HttpStatusCode, string> to map status codes to messages.
//
// Q5: Can you combine utility types together?
// A:  Absolutely! Common pattern: Partial<Omit<User, "id" | "createdAt">>
//     This creates a type where all fields except id/createdAt are optional.
//     Very useful for update DTOs in REST APIs.
//
// Q6: What is Required<T>?
// A:  The opposite of Partial — makes ALL properties required, even optional ones.
//     Useful when you need to guarantee all fields are present (e.g., after 
//     merging defaults with user input).
