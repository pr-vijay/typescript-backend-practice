// 1. UTILITY TYPES EXPLAINED
// ============================================================================

interface Employee {
  id: string;
  name: string;
  department: string;
  salary: number;
  isActive: boolean;
}

// --- Partial<T> ---
// Useful for HTTP PATCH requests (where a client only submits fields they want to change).
type UpdateEmployeeDto = Partial<Employee>;
// Equivalent to: { id?: string; name?: string; department?: string; salary?: number; isActive?: boolean; }
const patchData: UpdateEmployeeDto = { salary: 85000 }; // Only updating salary!

// --- Pick<T, Keys> ---
// Useful when you only need a few properties for a specific lightweight display component.
type EmployeeSummary = Pick<Employee, "name" | "department">;
const summary: EmployeeSummary = { name: "Bob", department: "Engineering" };

// --- Omit<T, Keys> ---
// Highly critical in backends! Used to strip sensitive data (like passwords) before sending to client.
type SafeEmployee = Omit<Employee, "salary" | "isActive">;
// SafeEmployee contains: id, name, department. Salary and isActive are removed.

// --- Readonly<T> ---
// Useful to freeze objects to prevent mutations in state management or parameters.
type ReadonlyEmployee = Readonly<Employee>;

// --- Record<Keys, Values> ---
// Useful for mapping dictionary key-value databases.
type UserRoleDescriptionMap = Record<"admin" | "editor" | "user", string>;
const roleMap: UserRoleDescriptionMap = {
  admin: "Has access to all database functions.",
  editor: "Can manage content, posts, and media.",
  user: "Standard read-only consumer access.",
};

